def legfix(c):
    """Planted boots never stretch a leg: when a hip gets too far from its ankle he sinks a little (the weight shift
    arcs), and boots off the ground are pulled back in reach."""
    def sockets(hy):
        out = {}
        for s in "LR":
            q = about(LEG[s][0], WAIST, c["pel"])
            q = about(q, TORSO, c["tor"])
            out[s] = (q[0] + c["hx"], q[1] + hy)
        return out

    def ankle(s):
        k = "fl" if s == "L" else "fr"
        return (LEG[s][1][0] + c[k + "_x"], LEG[s][1][1] + c[k + "_y"])

    planted = c["fl_y"] > -.5 and c["fr_y"] > -.5
    over = lambda hy: max(math.dist(sockets(hy)[s], ankle(s)) - LEG[s][2] * .999 for s in "LR")
    if planted:
        if over(c["hy"]) > 0:
            lo, hi = c["hy"], c["hy"] + 120
            for _ in range(24):
                mid = (lo + hi) / 2
                lo, hi = (mid, hi) if over(mid) > 0 else (lo, mid)
            c["hy"] = hi
    else:
        so = sockets(c["hy"])
        for s in "LR":
            k = "fl" if s == "L" else "fr"
            A, S, L = ankle(s), so[s], LEG[s][2] * .999
            d = math.dist(A, S)
            if d > L:                                          # pull the boot toward the hip
                f = L / d
                c[k + "_x"] += (S[0] + (A[0] - S[0]) * f) - A[0]
                c[k + "_y"] += (S[1] + (A[1] - S[1]) * f) - A[1]
    return c


def channels(name):
    """Every frame's channels for a clip: the drive, overlap springs on head and wrists (the links trail and settle),
    the planted-leg fix, and a one-shot's last frames eased exactly onto the rest pose. -> (first export frame, list)"""
    n, loop = CLIPS[name]
    warm = WARM.get(name, 0) if loop else 0
    total = warm + n if loop else n + 1
    S = {"hd": Spring(2.6, .5), "hr": Spring(2.4, .34), "hl": Spring(2.4, .34), "fr": Spring(2.2, .5),
         "fl": Spring(2.2, .5), "bsw": Spring(1.25, .22), "nk": Spring(2.8, .6)}
    out, prev = [], None
    pre = n if loop else 0
    for k in range(-pre, total):
        i = k % n if loop else k
        c = drive(name, i, n)
        first = prev is None
        if first:
            prev = dict(c)
        go = (lambda sp, v: sp.snap(v)) if first else (lambda sp, v: sp.step(v))
        vur, vul = (c["ur"] - prev["ur"]) * FPS, (c["ul"] - prev["ul"]) * FPS
        vfr, vfl = (c["ur"] + c["fr"] - prev["ur"] - prev["fr"]) * FPS, (c["ul"] + c["fl"] - prev["ul"] - prev["fl"]) * FPS
        vbx = (c["bx"] - prev["bx"]) * FPS
        raw = dict(c)
        lim = lambda v, L: L * math.tanh(v / L)
        c["hd"] = go(S["hd"], c["hd"])                         # the head, a moment late, a little past, back
        c["nk"] = go(S["nk"], c["nk"])
        c["fr"] += lim(go(S["fr"], -.035 * vur), 16)           # the forearm trails the upper arm ...
        c["fl"] += lim(go(S["fl"], -.03 * vul), 8) * (1 - c["ikl"])
        c["hr"] += lim(go(S["hr"], -.06 * vfr), 26)            # ... and the wrist trails the forearm
        c["hl"] += lim(go(S["hl"], -.05 * vfl), 12) * (1 - c["ikl"])
        c["fl"] = min(c["fl"], 3.0)                            # (the board arm's sleeve is drawn bent: it cannot fold tighter)
        c["bsw"] += lim(go(S["bsw"], .04 * vbx), 12) * min(1.0, abs(c["by"]) / 60.0)   # a carried board swings
        prev = raw
        if k < 0:
            continue
        if not loop:
            w = ease((n - i) / 10.0)
            for ch in CH:
                c[ch] = REST[ch] + (c[ch] - REST[ch]) * w
        out.append(legfix(c))
    return warm, out


