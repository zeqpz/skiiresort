def controls(c):
    """One frame's channels as control values: (bone, "rot") degrees on screen, (bone, "loc") art px on screen,
    (bone, "scl") in-plane width, (bone, <custom property>) a number."""
    q = {}
    q["torso", "rot"], q["torso", "loc"] = c["tor"], (c["hx"], c["hy"])
    q["hips", "rot"] = c["pel"]
    q["chest", "rot"], q["chest", "loc"] = c["ch"], (c["chx"], c["chy"])
    q["spine_fk.001", "rot"] = c["s1"]
    q["spine_fk.003", "rot"] = c["s3"]
    q["tweak_spine.003", "scl"] = 1 + .034 * c["br"]
    q["tweak_spine.002", "scl"] = 1 + .018 * c["br"]
    q["shoulder.L", "rot"], q["shoulder.R", "rot"] = -c["shrug_l"], c["shrug_r"]
    q["neck", "rot"] = c["nk"]
    q["head", "rot"], q["head", "loc"] = c["hd"], (c["hdx"], c["hdy"])
    q["face", "loc"] = (c["face_x"], c["face_y"])
    # the board: a turn about its buried tail, a swing about his grip, a move; his hand rides it
    th = c["board"] + c["bsw"]
    g1 = about(GRIP, BOARD_TAIL, c["board"])
    tail = about(BOARD_TAIL, g1, c["bsw"])
    q["board", "rot"] = th
    q["board", "loc"] = (tail[0] - BOARD_TAIL[0] + c["bx"], tail[1] - BOARD_TAIL[1] + c["by"])
    w1 = about(about(WRIST_L, BOARD_TAIL, c["board"]), g1, c["bsw"])
    q["hand_ik.L", "loc"] = (w1[0] - WRIST_L[0] + c["bx"] + c["wl_x"], w1[1] - WRIST_L[1] + c["by"] + c["wl_y"])
    q["hand_ik.L", "rot"] = c["wl_r"] + .7 * th
    q["upper_arm_parent.L", "IK_FK"] = 1 - max(0.0, min(1.0, c["ikl"]))
    for b, k in zip(ARM_L_FK, ("ul", "fl", "hl")):
        q[b, "rot"] = c[k]
    q["upper_arm_parent.R", "IK_FK"] = 1.0
    for b, k in zip(ARM_R_FK, ("ur", "fr", "hr")):
        q[b, "rot"] = c[k]
    q["foot_ik.L", "loc"], q["foot_ik.L", "rot"] = (c["fl_x"], c["fl_y"]), c["fl_r"]
    q["foot_ik.R", "loc"], q["foot_ik.R", "rot"] = (c["fr_x"], c["fr_y"]), c["fr_r"]
    for b in list(JIGGLE) + list(TWEAK_JIGGLE):                # the simulated bones: keyed at rest (the loops: on the
        q[b, "rot"], q[b, "loc"], q[b, "scl"] = 0.0, (0.0, 0.0), 1.0       # breeze), their swing baked later
        if c["gust"] and b in BREEZE:
            amp, k1, k2, ph = BREEZE[b]
            q[b, "rot"] = c["gust"] * amp * (.6 * math.sin(k1 * c["ga"] + ph) + .4 * math.sin(k2 * c["ga"] + 1.7 * ph))
    return q


class Action:
    """An action for one clip: an f-curve per control channel, a key on every frame (linear)."""

    def __init__(self, rig, name, poses, f0=0):
        self.rig, self.f0, self.n = rig, f0, len(poses)
        old = bpy.data.actions.get("yeti_" + name)
        if old:
            bpy.data.actions.remove(old)
        self.act = bpy.data.actions.new("yeti_" + name)
        self.act.use_fake_user = True
        self.fc = {}
        frames = [f0 + k for k in range(self.n)]
        for key in poses[0]:
            bone, kind = key
            cols = list(zip(*[self.values(bone, kind, p[key]) for p in poses]))
            path = f'pose.bones["{bone}"]' + {"rot": ".rotation_quaternion", "loc": ".location", "scl": ".scale"}.get(kind, f'["{kind}"]')
            for idx, col in enumerate(cols):
                fc = self.act.fcurves.new(path, index=idx, action_group=bone)
                fc.keyframe_points.add(self.n)
                fc.keyframe_points.foreach_set("co", [v for pair in zip(frames, col) for v in pair])
                fc.keyframe_points.foreach_set("interpolation", [1] * self.n)      # LINEAR
                fc.update()
                self.fc[bone, kind, idx] = fc

    def values(self, bone, kind, v):
        b = self.rig.data.bones[bone]
        inv = b.matrix_local.to_3x3().inverted()
        if kind == "rot":                                      # about the camera's axis, whatever the bone's roll
            ax = (inv @ Vector((0, -1, 0))).normalized()
            h = math.radians(v) / 2
            s = math.sin(h)
            return (math.cos(h), ax.x * s, ax.y * s, ax.z * s)
        if kind == "loc":
            return tuple(inv @ Vector((v[0] / 100.0, 0, -v[1] / 100.0)))
        if kind == "scl":
            return (v, 1.0, v)
        return (float(v),)

    def poke(self, bone, kind, k, v):
        """Re-key one control on the clip's k-th keyed frame."""
        for idx, val in enumerate(self.values(bone, kind, v)):
            fc = self.fc[bone, kind, idx]
            fc.keyframe_points[k].co[1] = val
            fc.update()

    def use(self):
        ad = self.rig.animation_data or self.rig.animation_data_create()
        ad.action = self.act


def bone_pt(rig, bn, p):
    """Where art point p (of the rest drawing) is right now, carried by DEF bone bn: art px."""
    pb = rig.pose.bones[bn]
    m = pb.matrix @ pb.bone.matrix_local.inverted()
    X, Z = u(*p)
    v = m @ Vector((X, 0, Z))
    return art(v.x, v.z)


def head_pt(rig, bn):
    v = rig.pose.bones[bn].matrix.col[3]
    return art(v.x, v.z)


def wrist_follow(rig, A, chans, gain=.5, most=32.0):
    """The board hand is an IK control that keeps its own angle; left alone the wrist breaks hard whenever the
    forearm swings (a see-through sliver opened between sleeve and cuff). It takes up part of the forearm's turn."""
    sc = bpy.context.scene
    pb = rig.pose.bones[D("forearm.L.001")]
    y0 = pb.bone.matrix_local.col[1]
    a0 = math.atan2(y0.z, y0.x)
    for k, c in enumerate(chans):
        if c["ikl"] <= 0:
            continue
        sc.frame_set(A.f0 + k)
        y = pb.matrix.col[1]
        d = math.degrees((math.atan2(y.z, y.x) - a0 + math.pi) % (2 * math.pi) - math.pi)
        c["wl_r"] += c["ikl"] * most * math.tanh(gain * d / most)
        A.poke("hand_ik.L", "rot", k, c["wl_r"] + .7 * (c["board"] + c["bsw"]))


REACH = 95.0                                          # art px shoulder to wrist he holds a joint to his lips at
PALM = (835, 548)                                     # the middle of his fist (art px, on the hand)
CONTACT_LOG = {}


def contact(rig, name, A, chans, warm):
    """Through each hit of the clip put the joint's mouth end ON his lips (yeti_rig.py's solve, on the Rigify FK
    arm): one turn of the hand for the whole hit, chosen so his wrist sits a comfortable REACH from the shoulder,
    then upper arm and forearm re-solved (two bones, the same bend) so the wrist lands where that hand puts the end
    on the lips; blended in and out over the window's ramps. Re-keys the three FK controls."""
    sc = bpy.context.scene
    n, loop = CLIPS[name]
    log = []
    UP, FO, HA = D("upper_arm.R"), D("forearm.R"), D("hand.R")

    def state(k):
        sc.frame_set(A.f0 + k)
        return (head_pt(rig, UP), head_pt(rig, FO), head_pt(rig, HA), bone_pt(rig, HA, JOINT_END), bone_pt(rig, D("face"), LIPS))

    def rekey(k):
        c = chans[k]
        for b, ch in zip(ARM_R_FK, ("ur", "fr", "hr")):
            A.poke(b, "rot", k, c[ch])

    cycles = range(0, len(chans), n) if loop else [0]
    for (a, b, c_, d) in CONTACT.get(name, []):
        km = (len(chans) - n if loop else 0) + (b + c_) // 2
        S, E, Wr, Jn, L = state(km)
        Tp, Pm = bone_pt(rig, HA, TIP), bone_pt(rig, HA, PALM)
        v = (Jn[0] - Wr[0], Jn[1] - Wr[1])
        tv, pv0 = (Tp[0] - Jn[0], Tp[1] - Jn[1]), (Pm[0] - Jn[0], Pm[1] - Jn[1])
        best = None
        for dth in range(-90, 91):
            vv = rot2(v, dth)
            T = (L[0] - vv[0], L[1] - vv[1])
            td = rot2(tv, dth)
            elev = math.degrees(math.atan2(-td[1], td[0]))      # the joint's angle above level, to his right = 0
            pv = rot2(pv0, dth)
            Lu, Lf = math.dist(S, E), math.dist(E, Wr)
            rd = math.dist(S, T)
            if not (abs(Lu - Lf) + 4 <= rd <= Lu + Lf - 4):    # out of the arm's reach
                continue
            cost = (abs(rd - REACH) + .3 * abs(dth) + 3 * max(0.0, abs(elev - 27) - 14)
                    + 4 * max(0.0, 30 - pv[0]) + 4 * max(0.0, 0 - pv[1]))
            if best is None or cost < best[0]:
                best = (cost, dth, round(elev, 1), round(rd, 1), tuple(round(q_) for q_ in pv))
        if best is None:
            raise RuntimeError(f"{name}: the joint cannot reach his lips")
        dth = best[1]
        print(f"     contact {name}: hand turn {dth}, joint {best[2]} deg above level, wrist {best[3]} px from the shoulder, palm {best[4]}, cost {best[0]:.1f}", flush=True)
        ang = lambda p_, q_: math.degrees(math.atan2(-(q_[1] - p_[1]), q_[0] - p_[0]))
        wrap = lambda r: (r + 180.0) % 360.0 - 180.0
        hand_dir = ang(Wr, Jn) + dth                             # the hand's direction (wrist -> joint end) in the hit
        side = None                                             # which way the elbow breaks: as keyed, and low

        def solve(k):
            """The three FK turns that put the joint's end on his lips on keyed frame k (from the pose as keyed)."""
            nonlocal side
            S, E, Wr, Jn, L = state(k)
            r = math.radians(hand_dir)
            vl = math.dist(Wr, Jn)
            T = (L[0] - vl * math.cos(r), L[1] + vl * math.sin(r))
            Lu, Lf = math.dist(S, E), math.dist(E, Wr)
            dist = max(1e-6, math.dist(S, T))
            dd = min(max(dist, abs(Lu - Lf) + 1), Lu + Lf - 1)
            ux, uy = (T[0] - S[0]) / dist, (T[1] - S[1]) / dist
            aa = (Lu * Lu - Lf * Lf + dd * dd) / (2 * dd)
            hh = math.sqrt(max(0.0, Lu * Lu - aa * aa))
            px, py = S[0] + aa * ux, S[1] + aa * uy
            cands = {+1: (px - hh * uy, py + hh * ux), -1: (px + hh * uy, py - hh * ux)}
            if side is None:
                side = min(cands, key=lambda q_: math.dist(cands[q_], E) - .5 * cands[q_][1])
            En = cands[side]
            Tn = (S[0] + dd * ux, S[1] + dd * uy)
            return (wrap(ang(S, En) - ang(S, E)), wrap(ang(En, Tn) - ang(E, Wr)), wrap(hand_dir - ang(Wr, Jn)),
                    math.dist(Jn, L), math.dist(S, Wr))

        solve(km)                                               # fixes the elbow's side from the middle of the hold
        for base in cycles:
            for i in range(a, d + 1):
                k = base + i
                w = ease((i - a) / max(1, b - a)) if i < b else (ease((d - i) / max(1, d - c_)) if i > c_ else 1.0)
                for it in range(3 if w == 1.0 else 1):          # (FK is exact: the 2nd and 3rd pass only polish)
                    dU, dF, dH, gap, reach = solve(k)
                    chans[k]["ur"] += w * dU
                    chans[k]["fr"] += w * (dF - dU)
                    chans[k]["hr"] += w * (dH - dF)
                    rekey(k)
                if base == cycles[-1]:
                    S, E, Wr, Jn, L = state(k)
                    log.append((i, round(w, 2), round(math.dist(Jn, L), 2), round(math.dist(S, Wr), 1)))
        log.append(("turn", best))
    CONTACT_LOG[name] = log
    return log


def bake_jiggle(rig, f0, f1, preroll=30):
    """Jiggle Physics' own bake over [f0, f1] into the current action (visual keys on the simulated controls)."""
    sc = bpy.context.scene
    sc.frame_start, sc.frame_end = f0, f1
    sc.jiggle.enable = True
    rig.jiggle.enable = True
    rig.jiggle.mute = False
    sc.jiggle.loop = False                                     # (loops: warm-up cycles are keyed instead)
    sc.jiggle.preroll = preroll
    sc.jiggle.bake_overwrite = True
    sc.jiggle.bake_nla = False
    only(rig)
    bpy.ops.object.mode_set(mode="POSE")
    try:
        r = bpy.ops.armature.jiggle_bake()
    finally:
        bpy.ops.object.mode_set(mode="OBJECT")
    if "FINISHED" not in r:
        raise RuntimeError("Jiggle Physics bake did not finish")


def tame_tweaks(act):
    """The limbs' middle tweaks keep only the spring on their PLACE (their baked turn would only twist the limb)."""
    for fc in list(act.fcurves):
        if any(f'["{b}"]' in fc.data_path for b in TWEAK_JIGGLE) and not fc.data_path.endswith(".location"):
            rest = 1.0 if (fc.data_path.endswith(".scale") or (fc.data_path.endswith("rotation_quaternion") and fc.array_index == 0)) else 0.0
            for kp in fc.keyframe_points:
                kp.co[1] = rest
            fc.update()


