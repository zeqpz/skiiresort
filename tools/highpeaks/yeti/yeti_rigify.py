def animate(rig):
    sc = bpy.context.scene
    sc.render.fps = FPS
    tracks = {}
    for name, (n, loop) in CLIPS.items():
        t0 = time.time()
        warm, chans = channels(name)
        A = Action(rig, name, [controls(c) for c in chans])
        A.use()
        wrist_follow(rig, A, chans)
        log = contact(rig, name, A, chans, warm)
        bake_jiggle(rig, 0, len(chans) - 1)
        tame_tweaks(A.act)
        tracks[name] = {"first": warm, "ember": [c["ember"] for c in chans[warm:]]}
        hits = [r for r in log if r[0] != "turn" and r[1] == 1.0]
        print(f"ANIM {name:13s} keyed {len(chans):3d} frames (export from {warm}), jiggle baked, {time.time() - t0:.1f} s"
              + (f"; joint end to lips through the hold: max {max(r[2] for r in hits):.3f} art px, pick {log[-1][1]}" if hits else ""),
              flush=True)
    sc.jiggle.enable = False
    rig["tracks"] = json.dumps(tracks)
    return tracks


# ---------------------------------------------------------------- keyed effects (sparks, kicked-up snow)

def effects(name, pts):
    """The clip's keyed sprites and live emits. pts(frame, point) -> art px of tip / mouth / boot_l / boot_r / board.
    -> (per-frame draws [kind, id, a, b, c, d, tx, ty, alpha], emits [[frame, kind]])"""
    rng = random.Random(4242 + sum(map(ord, name)))
    n, loop = CLIPS[name]
    last = n - 1 if loop else n
    draws = [dict() for _ in range(last + 1)]
    ids, base = {}, 0
    for kind, count, size in FX_KINDS:
        ids[kind] = (base, count, size)
        base += count
    used = {k: 0 for k in ids}
    kinds = [k for k, _, _ in FX_KINDS]
    live = []

    def emit(kind, fs, fe, path, spin=0.0, grow=(1, 1), fade_in=.12):
        if fs > last:
            return
        fe = fe if loop else min(fe, last)
        b0, count, size = ids[kind]
        oid = b0 + used[kind] % count + 1
        used[kind] += 1
        r0 = rng.uniform(0, 360)
        for f in range(fs, fe + 1):
            tt = (f - fs) / max(1, fe - fs)
            x, y = path(tt)
            g = grow[0] + (grow[1] - grow[0]) * tt
            al = (min(1.0, tt / fade_in) if fade_in else 1.0) * (1.0 if tt < .6 else (1 - tt) / .4)
            if al <= .003:
                continue
            th = math.radians(r0 + spin * tt)
            k = size * g
            draws[f % n if loop else f][oid] = [kinds.index(kind), oid] + [round(v, 3) for v in (
                k * math.cos(th), k * math.sin(th), -k * math.sin(th), k * math.cos(th), x, y, max(0.0, al))]

    def burst(i, cx, cy, count, reach=(180, 320), dur=26):
        for k in range(count):
            ang = 2 * math.pi * k / count + rng.uniform(-.3, .3)
            r = rng.uniform(*reach)
            emit("spark", i, i + dur, lambda t, ang=ang, r=r: (cx + r * math.cos(ang) * (1 - (1 - t) ** 2),
                                                               cy + r * math.sin(ang) * (1 - (1 - t) ** 2) + 40 * t * t),
                 260, (.5, 1.1), .05)

    def kick(i, spots=("boot_l", "boot_r"), reach=90):
        for spot, side in zip(spots, (-1, 1)):
            bx, by = pts(min(i, last), spot)
            emit("snowpuff", i, i + 22, lambda t, bx=bx, by=by, side=side: (bx + side * reach * t, by - 20 - 50 * t + 60 * t * t),
                 side * 30, (.4, 1.1), .05)

    if name == "idle":
        live += [[8, "wisp"], [52, "wisp"], [150, "exhale"], [186, "wisp"], [222, "wisp"]]
    elif name == "anticipation":
        live += [[4, "sweat"], [14, "wisp"]]
    elif name == "win":
        x, y = pts(14, "tip")
        burst(13, x, y, 6, (110, 210), 24)
        live.append([32, "wisp"])
    elif name == "big_win":
        for k, (t0, t1) in enumerate(((13, 31), (52, 66))):
            x, y = pts(min(t0 + 9, last), "mouth")
            burst(t0 + 2, x + 40, y - 350, 12 if k == 0 else 9, (200, 360))      # over his head, not on his face
            kick(t1)
        live += [[34, "wisp"], [86, "exhale"]]
    elif name == "bonus":
        for k, (t0, t1) in enumerate(((13, 33), (56, 67), (79, 91))):
            x, y = pts(min(t0 + 9, last), "mouth")
            burst(t0 + 2, x + 40, y - 350, 12 if k == 0 else 8, (200, 360) if k == 0 else (160, 290))
            if k == 0:
                kick(t1)
        kick(114, ("board", "board"), 70)                       # the board stabbed back into the snow
        live += [[36, "wisp"], [122, "exhale"]]
    elif name == "lose":
        live.append([42, "exhale"])
    live.sort()
    return [list(d.values()) for d in draws], live


