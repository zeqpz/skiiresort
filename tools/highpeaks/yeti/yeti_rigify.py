def head_weights(x, y):
    """The head and every face swap: rigid on the skull, the beanie flops from its band up, pom-pom, goggles, cheek
    fur, beard, the features (the face bone slides them), the neck stub."""
    pom = smooth(88, 62, math.hypot(x - 318, y - 100))
    yl = 320 - .3 * (x - 280)                                  # the beanie's lower edge (rising to the right)
    hat = smooth(-14, 96, yl - y) * (1 - pom)
    w = {D("pom"): pom, D("hat"): hat, HEAD: max(0.0, 1 - pom - hat)}

    def paint(bone, k):
        k = max(0.0, min(1.0, k))
        if k <= 0:
            return
        for b in w:
            w[b] *= 1 - k
        w[bone] = w.get(bone, 0.0) + k

    r = math.hypot((x - 477) / 128.0, (y - 214) / 76.0)
    paint(D("goggles"), .9 * smooth(1.12, .74, r))
    paint(D("cheek.L"), .85 * smooth(418, 318, x) * smooth(322, 366, y) * (1 - smooth(500, 556, y)))
    paint(D("cheek.R"), .85 * smooth(622, 700, x) * smooth(322, 366, y) * (1 - smooth(488, 540, y)))
    paint(D("beard"), .8 * smooth(505, 592, y))
    paint(NECK, smooth(598, 634, y))
    paint(D("face"), .9 * math.exp(-((x - 485) / 115.0) ** 2 - ((y - 425) / 95.0) ** 2) * max(0.0, 1 - 1.6 * hat - pom))
    return w


def finish(part, x, y, heat):
    """A vertex's weights: the bone-heat solve (heat: DEF bone -> weight, {} for the rigid pieces) with the rigid
    regions and the secondary bones laid over it."""
    p = (x, y)
    w = dict(heat)

    def paint(bone, k):
        k = max(0.0, min(1.0, k))
        if k <= 0:
            return
        for b in w:
            w[b] *= 1 - k
        w[bone] = w.get(bone, 0.0) + k

    if part == "board":
        return {D("board"): 1.0}
    if part == "snow":
        return {D("snow"): 1.0}
    if part in ("head", "face"):
        return head_weights(x, y)
    if part in ("leg_l", "leg_r"):
        s = "L" if part.endswith("l") else "R"
        paint(HIPS, 1 - smooth(1004, 1056, y))                 # the top of the trousers stays under the jacket
        paint(D("foot." + s), smooth(1285, 1335, y))           # the boot is rigid: all foot
        return w
    if part == "body":
        paint(D("shoulder.L"), (1 - smooth(300, 390, x)) * (1 - smooth(560, 650, y)) * .85)
        paint(D("shoulder.R"), smooth(645, 735, x) * (1 - smooth(560, 650, y)) * .85)
        paint(NECK, (1 - smooth(500, 548, y)) * smooth(400, 440, x) * (1 - smooth(600, 640, x)) * .7)
        paint(D("hood.L"), .6 * smooth(606, 520, y) * smooth(258, 298, x) * (1 - smooth(352, 388, x)))
        paint(D("hood.R"), .6 * smooth(606, 526, y) * smooth(598, 630, x) * (1 - smooth(702, 738, x)))
        paint(D("chest_fur"), .5 * math.exp(-((x - 517) / 100.0) ** 2 - ((y - 722) / 76.0) ** 2))
        paint(D("belly"), .55 * math.exp(-((x - 520) / 120.0) ** 2 - ((y - 935) / 90.0) ** 2))
        paint(D("hem.L"), .75 * smooth(902, 1000, y) * (1 - smooth(338, 386, x)))
        paint(D("hem.R"), .75 * smooth(902, 1000, y) * smooth(668, 716, x))
        paint(D("fur_hem"), .8 * smooth(1002, 1078, y) * smooth(326, 380, x) * (1 - smooth(690, 742, x)))
        paint(D("zip"), .9 * smooth(36, 18, math.hypot(x - 719, .8 * (y - 1008))))
        return w
    if part == "arm_l":
        d = math.hypot(x - 380, y - 545)
        if d < 75:                                              # the shoulder ball leans on the shoulder
            paint(D("shoulder.L"), .6 * smooth(75, 20, d))
        # the cuff and the hand are rigid on the hand (eased out toward the sleeve: a hard edge there tore specks
        # off the cuff when the hand turned against the forearm)
        paint(D("hand.L"), smooth(702, 772, y) * (1 - smooth(244, 288, x)))
        paint(D("cuff.L"), .7 * smooth(116, 64, x) * smooth(724, 750, y) * (1 - smooth(800, 826, y)))
        return w
    if part == "arm_r_up":                                      # shoulder to elbow: its lower end rigid under the ring
        t = tpos(p, MB["upper_arm.R"][1], MB["upper_arm.R"][2])
        k = smooth(.36, .64, t)
        w = {D("upper_arm.R"): 1 - k, D("upper_arm.R.001"): k}
        paint(D("shoulder.R"), .6 * smooth(75, 20, math.hypot(x - 660, y - 575)))
        # the fin: the strip of plain sleeve this piece carries up behind the forearm, cuff and hand. It moves with
        # THEM (the weights the piece over it has there), so it stays hidden however the elbow opens - rigid on the
        # upper arm it swung out into view as a green spike whenever the forearm left it
        fin = smooth(716, 744, x) * smooth(664, 620, y)
        if fin > 0:
            for b in w:
                w[b] *= 1 - fin
            for b, v in finish("arm_r_lo", x, y, {}).items():
                w[b] = w.get(b, 0.0) + v * fin
        return w
    if part == "arm_r_lo":                                      # the elbow ring (rigid, turning in place), forearm,
        t = tpos(p, MB["forearm.R"][1], MB["forearm.R"][2])     # then cuff, hand and joint rigid on the hand
        k = smooth(.42, .72, t)
        w = {D("forearm.R"): 1 - k, D("forearm.R.001"): k}
        paint(D("hand.R"), smooth(668, 616, y))
        paint(D("cuff.R"), .7 * smooth(888, 924, x) * smooth(588, 606, y) * (1 - smooth(640, 662, y)))
        return w
    raise KeyError(part)


