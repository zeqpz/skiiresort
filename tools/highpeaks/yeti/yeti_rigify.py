def run(steps, clips=None, step=6):
    blend = os.path.join(OUT, "yeti_rigify.blend")
    if "build" in steps:
        STATE["rig"] = build()
    elif "rig" not in STATE:
        enable_addons()
        bpy.ops.wm.open_mainfile(filepath=blend)
        STATE["rig"] = bpy.data.objects["yeti"]
    rig = STATE["rig"]
    if "rest" in steps:
        render_rest(rig, os.path.join(OUT, "renders", "rest.png"))
    if "animate" in steps:
        animate(rig)
    if "build" in steps or "animate" in steps:
        bpy.ops.wm.save_as_mainfile(filepath=blend)
    if "export" in steps:
        export(rig)
    if "render" in steps:
        render(rig, clips or list(CLIPS), step, KEY_FRAMES)
    if "zoom" in steps:
        render_zoom(rig, clips)
    if "arms" in steps:                                        # each arm alone, and the whole figure, on a clear
        global QA_RES                                          # page at twice the size (qa_holes_rig.py reads them)
        keep, QA_RES = QA_RES, (QA_RES[0] * 2, QA_RES[1] * 2)
        for grp, names in (("arm_r", ["arm_r_up", "arm_r_lo"]), ("arm_l", ["arm_l"]), ("all", None)):
            render(rig, clips or list(CLIPS), step, None, names, os.path.join("qa_arms", grp))
        QA_RES = keep
        qa_camera()


if __name__ == "__main__" and "--" in sys.argv:
    args = sys.argv[sys.argv.index("--") + 1:]
    run((args[0] if args else "build,animate,export,render").split(","), args[1].split(",") if len(args) > 1 and args[1] else None,
        int(args[2]) if len(args) > 2 else 6)
