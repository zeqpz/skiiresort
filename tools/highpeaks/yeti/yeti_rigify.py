class Jump:
    """One jump: crouch (`dip` px), a fast push, `air` frames off the ground reaching `h` px, an impact landing into
    a `squash`, the recover with a small overshoot. t0 = the frame his boots leave the snow."""

    def __init__(self, t0, h, air, dip, squash=None, pre=9, push=3):
        self.t0, self.h, self.air, self.dip = t0, h, air, dip
        self.sq = squash if squash is not None else .85 * dip
        self.pre, self.push = pre, push
        self.t1 = t0 + air                                     # touch-down

    def hy(self, i):
        t0, t1 = self.t0, self.t1
        if i <= t0 - self.push:
            return kf(i, (t0 - self.push - self.pre, 0), (t0 - self.push - 1.5, self.dip), (t0 - self.push, self.dip * .96))
        if i <= t0:
            s = (i - (t0 - self.push)) / self.push
            return self.dip * .96 * (1 - s * s)                # the push: gathering speed
        if i <= t1:
            s = (i - t0) / self.air
            return -self.h * (1 - (2 * s - 1) ** 2)            # ballistic
        if i <= t1 + 4:
            s = (i - t1) / 4.0
            return self.sq * (1 - (1 - s) ** 2)                # the impact: stopping
        return kf(i, (t1 + 4, self.sq), (t1 + 10, -5), (t1 + 15, 1.5), (t1 + 19, 0))

    def up(self, i):
        """0 on the ground, 1 through the middle of the air time; back to 0 three frames before he lands (the legs
        reach for the snow: straight on touch-down, then they give)."""
        return bump(i, self.t0, self.t1 - 3) ** .7 if self.t0 < i < self.t1 - 3 else 0.0

    def airborne(self, i):
        return self.t0 < i < self.t1

    def chy(self, i, stretch=34):
        """The torso's squash (+) and stretch (-) through the jump."""
        t0, t1 = self.t0, self.t1
        return kf(i, (t0 - self.push - self.pre, 0), (t0 - self.push - 1, .36 * self.dip), (t0 + 1, -stretch),
                  (t0 + 4, -.8 * stretch), (t0 + self.air * .5, -.2 * stretch), (t1 - 1, -.62 * stretch),
                  (t1 + 4, .4 * self.sq), (t1 + 10, -6), (t1 + 16, 0))

    def head(self, i):
        """The head trails the body: it lags on the push, floats over the top, drops late on the landing."""
        t0, t1 = self.t0, self.t1
        return kf(i, (t0 - self.push - self.pre, 0), (t0 - self.push, 7), (t0 + 1, 15), (t0 + 6, -7),
                  (t0 + self.air * .5 + 2, -9), (t1, -3), (t1 + 2, 5), (t1 + 6, 17), (t1 + 12, -3), (t1 + 18, 0))


