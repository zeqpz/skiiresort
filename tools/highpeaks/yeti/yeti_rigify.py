"""High Peaks: the yeti on a RIGIFY control rig with JIGGLE PHYSICS secondary motion (2026-11-23), replacing the
hand-built 25-bone skeleton of yeti_rig.py (left in place; this file imports its art constants, materials and curve
helpers). Same cut parts (art/highpeaks/yeti/parts), same flat look (emission-lit pictures on grid meshes in the XZ
plane, orthographic camera), same LIVE rig format out (rig/rig.json, geo.bin, <clip>.bin), so frontend/charrig.js plays
it unchanged and yeti_pack.py packs it unchanged.

What is different
  * the skeleton is a Rigify metarig emitted from the scripted joint positions (art px) and GENERATED by Rigify:
      spines.basic_spine (4 bones) + spines.super_head (neck, head), limbs.arm x2 and limbs.leg x2 with TWO deform
      segments per limb section (segments=2, bbones=1: real bones, so the exporter needs no b-bone sampling),
      basic.super_copy for shoulders, face, board, snow and the secondary bones. Only the generated rig's DEF- bones
      that carry weight are exported (47 of the rig's 261 bones).
  * the pieces are bound to the DEF bones: bone-heat automatic weights (parent_set ARMATURE_AUTO, a throw-away copy of
      each part with only its own bones deforming) where the art bends - torso, both legs, the board arm - and
      explicit rigid weights where it must not shear - boots, board, snow, head / faces, the two-piece joint arm (its
      elbow still turns about the middle of its ring: ELBOW_R). Secondary bones are painted in by formula on top.
  * secondary motion is simulated, not keyed: Jiggle Physics on the controls of pom-pom, beanie, goggles, cheek fur,
      beard, hood rolls, chest fur, belly, fur hem, jacket hems, zipper pull, both cuffs and the limbs' mid tweaks,
      baked per clip with armature.jiggle_bake (loops are baked over extra warm-up cycles and the last one exported,
      so they are periodic; one-shots start settled on the rest pose). The primary overlap on the keyed links (head
      and neck a moment late, forearm trailing upper arm, wrist trailing forearm, a carried board swinging) is a
      small spring filter on the channels in channels(), not the add-on.
  * every clip is re-authored on the control rig: IK feet (planted unless he jumps), IK board hand that rides the
      board, FK joint arm (with the old contact solve for the puff: the joint's end ON his lips), torso / hips / chest
      / neck / head controls, tweak scale for breathing; channels are in screen terms (art px, degrees
      counter-clockwise) and mapped onto whatever local axes Rigify gave each control.

Headless (do NOT pass --factory-startup: Rigify and Jiggle Physics live in the user profile):
  blender -b --python tools/highpeaks/yeti/yeti_rigify.py -- build,animate,export,render [clips] [step]
-> art/highpeaks/yeti/rig_build/yeti_rigify.blend, rig/ (rig.json, geo.bin, <clip>.bin), qa_points.json,
   renders/<clip>/NNNN.png"""
