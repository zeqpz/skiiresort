def make_metarig():
    ad = bpy.data.armatures.new("metarig")
    meta = bpy.data.objects.new("metarig", ad)
    bpy.context.scene.collection.objects.link(meta)
    only(meta)
    bpy.ops.object.mode_set(mode="EDIT")
    for name, h, t, par, con, rt in META_BONES:
        b = ad.edit_bones.new(name)
        (hx, hz), (tx, tz) = u(*h), u(*t)
        b.head, b.tail = (hx, 0, hz), (tx, 0, tz)
        b.align_roll((0, -1, 0))
    for s, x in HEELS:                                         # the leg rig wants a heel bone: across the sole
        b = ad.edit_bones.new("heel.02." + s)
        hx, hz = u(x, 1450)
        b.head, b.tail = (hx, -.2, hz), (hx, .2, hz)
        b.parent = ad.edit_bones["foot." + s]
    for name, h, t, par, con, rt in META_BONES:
        if par:
            ad.edit_bones[name].parent = ad.edit_bones[par]
            ad.edit_bones[name].use_connect = con
    bpy.ops.object.mode_set(mode="OBJECT")
    for name, h, t, par, con, rt in META_BONES:
        pb = meta.pose.bones[name]
        if rt:
            pb.rigify_type = rt
        prm = pb.rigify_parameters
        if rt.startswith("limbs.arm") or rt.startswith("limbs.leg"):
            prm.segments = 2                                   # two real deform bones per limb section
            prm.bbones = 1                                     # no b-bone curvature (it is not a bone transform)
            prm.rotation_axis = "automatic"
        elif rt == "spines.super_head":
            prm.connect_chain = True
            prm.bbones = 1
        elif rt == "spines.basic_spine":
            prm.bbones = 1
        elif rt == "limbs.simple_tentacle":
            prm.bbones = 1
            prm.copy_rotation_axes = (False, False, False)
    return meta


def generate(meta):
    import rigify.generate as g
    only(meta)
    t0 = time.time()
    g.generate_rig(bpy.context, meta)
    rig = meta.data.rigify_target_rig
    rig.name = "yeti"
    print(f"RIGIFY generated {len(rig.pose.bones)} bones, {sum(1 for b in rig.data.bones if b.use_deform)} deform, "
          f"in {time.time() - t0:.2f} s", flush=True)
    meta.hide_render = True
    meta.hide_viewport = True
    rig.show_in_front = True
    for pb in rig.pose.bones:
        if not pb.name.startswith(("ORG-", "MCH-", "DEF-")):
            pb.rotation_mode = "QUATERNION"
            for c in list(pb.constraints):                     # the tentacle's (switched-off) copy-rotation
                if c.type == "COPY_ROTATION" and pb.name in JIGGLE:
                    pb.constraints.remove(c)
    P = rig.pose.bones
    P["upper_arm_parent.R"]["IK_FK"] = 1.0                     # the joint arm is FK (the puff folds it right over)
    rig.update_tag()
    for ob in bpy.data.objects:                                # Rigify's control widgets never render
        if ob.name.startswith("WGT-"):
            ob.hide_render = True
    return rig


def heat_weights(ob, rig, bones):
    """Bone-heat weights for a part from a throw-away copy (only `bones` deform during the solve)."""
    tmp = ob.copy()
    tmp.data = ob.data.copy()
    bpy.context.scene.collection.objects.link(tmp)
    tmp.parent = None
    for m in list(tmp.modifiers):
        tmp.modifiers.remove(m)
    for g in list(tmp.vertex_groups):
        tmp.vertex_groups.remove(g)
    tmp.location = (0, .3, 0)                                  # off the bones' plane: every vertex sees every bone
    saved = {b.name: b.use_deform for b in rig.data.bones}
    for b in rig.data.bones:
        b.use_deform = b.name in bones
    only(tmp)
    rig.select_set(True)
    bpy.context.view_layer.objects.active = rig
    bpy.ops.object.parent_set(type="ARMATURE_AUTO")
    for b in rig.data.bones:
        b.use_deform = saved[b.name]
    names = {g.index: g.name for g in tmp.vertex_groups}
    out = [{names[g.group]: g.weight for g in v.groups if g.weight > 1e-4} for v in tmp.data.vertices]
    bad = sum(1 for w in out if not w)
    me = tmp.data
    bpy.data.objects.remove(tmp, do_unlink=True)
    bpy.data.meshes.remove(me)
    if bad:
        raise RuntimeError(f"bone heat left {bad} vertices of {ob.name} unweighted")
    return out


def bind(ob, part, rig, heat_bones=None):
    heat = heat_weights(ob, rig, heat_bones) if heat_bones else None
    for g in list(ob.vertex_groups):
        ob.vertex_groups.remove(g)
    groups, used = {}, set()
    for vi, v in enumerate(ob.data.vertices):
        ax, ay = art(v.co.x, v.co.z)
        w = top4(finish(part, ax, ay, heat[vi] if heat else {}))
        for bn, wt in w.items():
            g = groups.get(bn) or ob.vertex_groups.new(name=bn)
            groups[bn] = g
            g.add([vi], wt, "REPLACE")
            used.add(bn)
    return used


